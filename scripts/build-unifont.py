#!/usr/bin/env python3
"""Split GNU Unifont (~4.7 MB) into small unicode-range chunks.

Browsers download a chunk only when the page uses a character in its range, so the CRT levels
get Unifont as a per-character fallback for nearly the whole Basic Multilingual Plane without
loading the whole font.

    npm run fonts:unifont   (needs: pip install fonttools brotli)

Writes apps/client/public/fonts/unifont/*.woff2 and apps/client/src/fonts/unifont.css.
Commit the output so nobody needs Python just to build the client.
"""
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'node_modules/@fontsource/unifont/files/unifont-latin-400-normal.woff2'
OUT_DIR = ROOT / 'apps/client/public/fonts/unifont'
CSS_OUT = ROOT / 'apps/client/src/fonts/unifont.css'
FAMILY = 'DMD Unifont'

# Hand-picked chunk boundaries: small chunks where a game UI is likely to reach
# (symbols, box drawing, arrows), bigger ones for large scripts like CJK.
BOUNDARIES = [
    0x0000, 0x0250, 0x0370, 0x0530, 0x0900, 0x1000, 0x1E00, 0x2000, 0x2100, 0x2190,
    0x2300, 0x2500, 0x2600, 0x2700, 0x2800, 0x2900, 0x2C00, 0x3000, 0x3100, 0x3400,
    0x4E00, 0x5A00, 0x6600, 0x7200, 0x7E00, 0x8A00, 0x9600, 0xA000, 0xAC00, 0xD800,
    0xE000, 0xF900, 0x10000,
]


def main() -> int:
    if not SRC.exists():
        print(f'Missing {SRC}. Run npm install first.', file=sys.stderr)
        return 1
    # Decoding the WOFF2 source is slow in pure Python (~2 min), so decode it once to TTF bytes
    # and re-open those cheaply for each chunk.
    print('Decoding source font (slow, once)…', flush=True)
    src = TTFont(SRC)
    src.flavor = None
    ttf = io.BytesIO()
    src.save(ttf)
    ttf_bytes = ttf.getvalue()
    cmap = src.getBestCmap()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob('*.woff2'):
        old.unlink()

    faces = []
    total = 0
    for lo, hi in zip(BOUNDARIES, BOUNDARIES[1:]):
        cps = sorted(c for c in cmap if lo <= c < hi)
        if not cps:
            continue
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = []
        opts.name_IDs = ['*']
        opts.notdef_outline = False
        sub = subset.Subsetter(opts)
        font = TTFont(io.BytesIO(ttf_bytes))
        sub.populate(unicodes=cps)
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = 'woff2'
        font.save(buf)
        name = f'unifont-{lo:04x}-{hi - 1:04x}.woff2'
        (OUT_DIR / name).write_bytes(buf.getvalue())
        total += buf.tell()
        faces.append(
            '@font-face {\n'
            f"  font-family: '{FAMILY}';\n"
            f"  src: url('/fonts/unifont/{name}') format('woff2');\n"
            '  font-display: swap;\n'
            f'  unicode-range: U+{cps[0]:04X}-{cps[-1]:04X};\n'
            '}\n'
        )
        print(f'{name:32} {len(cps):6} glyphs {buf.tell() / 1024:8.1f} KB', flush=True)

    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)
    CSS_OUT.write_text(
        '/* Generated by scripts/build-unifont.py. Do not edit by hand. */\n'
        '/* GNU Unifont, SIL OFL 1.1 (via @fontsource/unifont). */\n\n' + '\n'.join(faces)
    )
    print(f'{len(faces)} chunks, {total / 1024 / 1024:.2f} MB total -> {CSS_OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
